/** Distant one-shots placed around the listener. rate = expected calls per minute at full weight. */
interface WildEntry {
  id: string; rate: number; dist: [number, number]; height?: [number, number];
  weight: (h: number, w: Weather, hab: Record<string, number>, dread: number) => number;
}
const band = (h: number, from: number, to: number, soft = 1): number => {
  // 1 inside [from, to) (wrapping midnight), soft ramps of `soft` hours on both sides
  const inside = (x: number) => (from <= to ? x >= from && x < to : x >= from || x < to);
  if (inside(h)) return 1;
  const d = Math.min(...[from, to].map((e) => { const a = Math.abs(h - e); return Math.min(a, 24 - a); }));
  return Math.max(0, 1 - d / soft);
};
