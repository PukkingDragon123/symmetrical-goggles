const SEND: Record<SoundCat, number> = { sfx: 0.35, amb: 0, ui: 0, voice: 0.25, music: 0 };
const MAX_VOICES = 64;
const MAX_PER_ID = 8;

const _v = new THREE.Vector3();
const _q = new THREE.Quaternion();
function toVec(p: Vec3Like, out = new THREE.Vector3()): THREE.Vector3 {
  return Array.isArray(p) ? out.set(p[0], p[1], p[2]) : out.set(p.x, p.y, p.z);
}

class VoiceImpl implements Voice {
  playing = true;
  onEnded?: () => void;
  src: AudioBufferSourceNode | null = null;
  gain: GainNode; fade: GainNode; send: GainNode;
  panner: PannerNode | null = null; filter: BiquadFilterNode | null = null;
  pos = new THREE.Vector3();
  baseVol: number; rate: number; occ = 0; distGain = 1; stopped = false;
  constructor(public eng: AudioEngine, public id: string, public def: SoundDef, opts: PlayOpts, out: AudioNode, spatial: boolean) {
    const ctx = eng.ctx!;
    this.baseVol = def.vol * (opts.vol ?? 1);
    const j = def.rateJitter ?? 0;
    this.rate = (opts.rate ?? 1) * (1 + (Math.random() * 2 - 1) * j);
    this.gain = ctx.createGain();
    this.gain.gain.value = this.baseVol;
    this.fade = ctx.createGain();
    this.send = ctx.createGain();
    this.send.gain.value = opts.reverb ?? SEND[def.cat] ?? 0;
    let node: AudioNode = this.gain;
    if (spatial) {
      this.filter = ctx.createBiquadFilter();
      this.filter.type = 'lowpass';
      this.filter.frequency.value = 20000;
      this.filter.Q.value = 0.5;
      const p = (this.panner = ctx.createPanner());
      p.panningModel = 'HRTF';
      p.distanceModel = 'inverse';
      p.refDistance = def.refDist ?? 2;
      p.maxDistance = def.maxDist ?? 60;
      p.rolloffFactor = 1;
      if (opts.pos) this.setPos(opts.pos);
      node.connect(this.filter);
      this.filter.connect(p);
      node = p;
    }
    node.connect(this.fade);
    this.fade.connect(out);
    this.fade.connect(this.send);
    this.send.connect(eng.reverbIn!);
    if (spatial) this.updateSpatial(true);
  }
  start(buf: AudioBuffer, opts: PlayOpts, loop: boolean): void {
    if (this.stopped) return;
    const ctx = this.eng.ctx!;
    const s = (this.src = ctx.createBufferSource());
    s.buffer = buf;
    s.loop = loop;
    s.playbackRate.value = this.rate;
    s.connect(this.gain);
    const t = ctx.currentTime + (opts.delay ?? 0);
    const fi = opts.fadeIn ?? (loop ? 0.05 : 0);
    if (fi > 0) {
      this.fade.gain.setValueAtTime(0, t);
      this.fade.gain.linearRampToValueAtTime(1, t + fi);
    }
    const off = opts.offset ?? (loop ? Math.random() * buf.duration : 0);
    s.start(t, Math.min(off, Math.max(0, buf.duration - 0.01)));
    s.onended = () => this.cleanup();
  }
  setPos(p: Vec3Like): void {
    toVec(p, this.pos);
    const pn = this.panner;
    if (!pn) return;
    const t = this.eng.ctx!.currentTime;
    if (pn.positionX) {
      pn.positionX.setTargetAtTime(this.pos.x, t, 0.02);
      pn.positionY.setTargetAtTime(this.pos.y, t, 0.02);
      pn.positionZ.setTargetAtTime(this.pos.z, t, 0.02);
    } else pn.setPosition(this.pos.x, this.pos.y, this.pos.z);
  }
  setVol(v: number, ramp = 0.05): void {
    this.baseVol = this.def.vol * v;
    this.applyGain(ramp);
  }
  setRate(r: number, ramp = 0.05): void {
    this.rate = r;
    if (this.src) this.src.playbackRate.setTargetAtTime(r, this.eng.ctx!.currentTime, Math.max(0.001, ramp / 3));
  }
  applyGain(ramp = 0.05): void {
    const occGain = 1 - 0.65 * this.occ;
    this.gain.gain.setTargetAtTime(this.baseVol * occGain * this.distGain, this.eng.ctx!.currentTime, Math.max(0.001, ramp / 3));
  }
  /** Distance fade near maxDist, air absorption and occlusion low-pass. */
  updateSpatial(now = false): void {
    if (!this.panner || !this.filter) return;
    const e = this.eng;
    const d = this.pos.distanceTo(e.listenerPos);
    const maxD = this.def.maxDist ?? 60;
    this.distGain = 1 - THREE.MathUtils.smoothstep(d, maxD * 0.75, maxD);
    this.occ = e.occlusionFn ? THREE.MathUtils.clamp(e.occlusionFn(this.pos), 0, 1) : 0;
    const air = 20000 / (1 + d / 120);                      // distant sounds lose their top end
    const occCut = 20000 * Math.pow(500 / 20000, this.occ);  // 0 -> 20 kHz, 1 -> 500 Hz
    const f = Math.max(300, Math.min(air, occCut, 20000));
    const t = e.ctx!.currentTime;
    if (now) this.filter.frequency.value = f;
    else this.filter.frequency.setTargetAtTime(f, t, 0.08);
    this.applyGain(now ? 0.001 : 0.15);
  }
  stop(fade = 0.05): void {
    if (this.stopped) return;
    this.stopped = true;
    const ctx = this.eng.ctx!;
    const t = ctx.currentTime;
    if (!this.src) { this.cleanup(); return; }
    this.fade.gain.cancelScheduledValues(t);
    this.fade.gain.setValueAtTime(this.fade.gain.value, t);
    this.fade.gain.linearRampToValueAtTime(0, t + Math.max(0.005, fade));
    try { this.src.stop(t + Math.max(0.005, fade) + 0.02); } catch { /* already stopped */ }
  }
  cleanup(): void {
    if (!this.playing) return;
    this.playing = false;
    this.stopped = true;
    try { this.src?.disconnect(); } catch { /* */ }
    this.fade.disconnect();
    this.send.disconnect();
    this.eng.voices.delete(this);
    this.onEnded?.();
  }
}

export class AudioEngine {
  ctx: AudioContext | null = null;
  master: GainNode | null = null;
  buses: Partial<Record<SoundCat, GainNode>> = {};
  ambOut: GainNode | null = null;          // outdoor ambience goes through the indoor muffler
  ambFilter: BiquadFilterNode | null = null;
  reverbIn: GainNode | null = null;
  private convs: { conv: ConvolverNode; out: GainNode }[] = [];
  private convIdx = 0;
  zone: ReverbZone = 'outdoor';
  voices = new Set<VoiceImpl>();
  listenerPos = new THREE.Vector3();
  listenerFwd = new THREE.Vector3(0, 0, -1);
  occlusionFn: ((pos: THREE.Vector3) => number) | null = null;
  baseUrl = '';
  private buffers = new Map<string, AudioBuffer>();
  private loading = new Map<string, Promise<AudioBuffer | null>>();
  private lastPick = new Map<string, number>();
  private vols: Record<string, number> = { master: 1, sfx: 1, amb: 1, ui: 1, voice: 1, music: 1 };
  private amb = new Map<string, { target: number; cur: number; voices: Voice[] }>();
  private hour = 12;
  private weather: Weather = { rain: 0, wind: 0, storm: 0 };
  private habitat: Record<string, number> = { lake: 0, creek: 0 };
  private dread = 0;
  private indoors = 0;
  private wildTimers = new Map<string, number>();
  private lastT = 0;
  private spatialTick = 0;
  wildlifeEnabled = true;
  private armed = false;

  constructor() {
    if (typeof window !== 'undefined') this.armAutoUnlock();
  }

  /** Create the context (suspended until a gesture). Safe to call early: decoding works while suspended. */
  init(): AudioContext {
    if (this.ctx) return this.ctx;
    const ctx = (this.ctx = new AudioContext({ latencyHint: 'interactive' }));
    const comp = ctx.createDynamicsCompressor();      // gentle bus glue / safety limiter
    comp.threshold.value = -10; comp.knee.value = 8; comp.ratio.value = 4; comp.attack.value = 0.004; comp.release.value = 0.2;
    this.master = ctx.createGain();
    this.master.connect(comp).connect(ctx.destination);
    for (const c of ['sfx', 'amb', 'ui', 'voice', 'music'] as SoundCat[]) {
      const g = ctx.createGain();
      g.connect(this.master);
      this.buses[c] = g;
    }
    this.ambFilter = ctx.createBiquadFilter();
    this.ambFilter.type = 'lowpass';
    this.ambFilter.frequency.value = 20000;
    this.ambOut = ctx.createGain();
    this.ambOut.connect(this.ambFilter).connect(this.buses.amb!);
    this.reverbIn = ctx.createGain();
    for (let i = 0; i < 2; i++) {
      const conv = ctx.createConvolver();
      const out = ctx.createGain();
      out.gain.value = 0;
      this.reverbIn.connect(conv).connect(out).connect(this.buses.sfx!);
      this.convs.push({ conv, out });
    }
    this.applyVolumes();
    this.setReverb(this.zone, 0);
    return ctx;
  }

  private armAutoUnlock(): void {
    if (this.armed) return;
    this.armed = true;
    const go = () => { this.unlock(); };
    for (const ev of ['pointerdown', 'keydown', 'touchend']) window.addEventListener(ev, go, { once: true, capture: true });
  }

  /** Call from a user gesture (click / key). Creates and resumes the AudioContext. */
  async unlock(): Promise<void> {
    const ctx = this.init();
    if (ctx.state !== 'running') {
      try { await ctx.resume(); } catch { /* not a gesture yet */ }
    }
  }

  get unlocked(): boolean { return this.ctx?.state === 'running'; }

  setPaused(p: boolean): void {
    if (!this.ctx) return;
    if (p) void this.ctx.suspend(); else void this.ctx.resume();
  }

  // ------------------------------------------------------------------ loading
  private url(f: string): string {
    if (this.baseUrl) return this.baseUrl.replace(/\/?$/, '/') + f;
    return typeof document !== 'undefined' ? new URL(f, document.baseURI).href : f;
  }

  private load(file: string): Promise<AudioBuffer | null> {
    const have = this.buffers.get(file);
    if (have) return Promise.resolve(have);
    let p = this.loading.get(file);
    if (!p) {
      const ctx = this.init();
      p = fetch(this.url(file))
        .then((r) => { if (!r.ok) throw new Error(`${r.status} ${file}`); return r.arrayBuffer(); })
        .then((ab) => ctx.decodeAudioData(ab))
        .then((b) => { this.buffers.set(file, b); return b; })
        .catch((e) => { console.warn('[audio] load failed', file, e); return null; });
      this.loading.set(file, p);
    }
    return p;
  }

  /** Fetch + decode every variation of these sound ids (all ids if omitted). */
  preload(ids: string[] = Object.keys(SOUNDS)): Promise<void> {
    const files = ids.flatMap((id) => SOUNDS[id]?.files ?? []);
    return Promise.all(files.map((f) => this.load(f))).then(() => undefined);
  }

  isLoaded(id: string): boolean {
    return !!SOUNDS[id]?.files.every((f) => this.buffers.has(f));
  }

  // ------------------------------------------------------------------ playing
  play(id: string, opts: PlayOpts = {}): Voice | null {
    const def = SOUNDS[id];
    if (!def) { console.warn('[audio] unknown sound', id); return null; }
    const ctx = this.init();
    if (ctx.state === 'closed') return null;
    const spatial = !!opts.pos;
    if (spatial) {
      const d = toVec(opts.pos!, _v).distanceTo(this.listenerPos);
      if (d > (def.maxDist ?? 60) && !(opts.loop ?? def.loop)) return null; // inaudible one-shot: skip
    }
    if (this.voices.size >= MAX_VOICES) this.steal();
    let same = 0;
    let oldest: VoiceImpl | null = null;
    for (const v of this.voices) if (v.id === id && !v.stopped) { same++; oldest ??= v; }
    if (same >= MAX_PER_ID && oldest) oldest.stop(0.03);
    const n = def.files.length;
    let k = opts.variant ?? Math.floor(Math.random() * n);
    if (opts.variant === undefined && n > 1 && k === this.lastPick.get(id)) k = (k + 1 + Math.floor(Math.random() * (n - 1))) % n;
    this.lastPick.set(id, k);
    const file = def.files[k % n];
    const loop = opts.loop ?? !!def.loop;
    const out = def.cat === 'amb' ? this.buses.amb! : this.buses[def.cat]!;
    const v = new VoiceImpl(this, id, def, opts, out, spatial);
    this.voices.add(v);
    const buf = this.buffers.get(file);
    if (buf) v.start(buf, opts, loop);
    else {
      const asked = ctx.currentTime;
      void this.load(file).then((b) => {
        if (!b || v.stopped) { v.cleanup(); return; }
        // a late one-shot is worse than none: drop it if decoding took too long
        if (!loop && ctx.currentTime - asked > 0.35 + (opts.delay ?? 0)) { v.cleanup(); return; }
        v.start(b, opts, loop);
      });
    }
    return v;
  }

  private steal(): void {
    // drop the quietest non-looping voice
    let best: VoiceImpl | null = null;
    let bestG = Infinity;
    for (const v of this.voices) {
      if (v.src?.loop) continue;
      const g = v.baseVol * v.distGain;
      if (g < bestG) { bestG = g; best = v; }
    }
    best?.stop(0.02);
  }

  stopAll(fade = 0.1): void {
    for (const v of [...this.voices]) v.stop(fade);
    for (const a of this.amb.values()) a.voices = [];
  }

  // ------------------------------------------------------------------ listener + per-frame update
  /** Call every frame with the active camera. Also advances fades, wildlife and spatial filters. */
  setListener(cam: THREE.Object3D): void {
    if (!this.ctx) return;
    cam.updateMatrixWorld();
    cam.getWorldPosition(this.listenerPos);
    cam.getWorldQuaternion(_q);
    this.listenerFwd.set(0, 0, -1).applyQuaternion(_q);
    const up = _v.set(0, 1, 0).applyQuaternion(_q);
    const L = this.ctx.listener;
    const p = this.listenerPos, f = this.listenerFwd;
    if (L.positionX) {
      L.positionX.value = p.x; L.positionY.value = p.y; L.positionZ.value = p.z;
      L.forwardX.value = f.x; L.forwardY.value = f.y; L.forwardZ.value = f.z;
      L.upX.value = up.x; L.upY.value = up.y; L.upZ.value = up.z;
    } else {
      L.setPosition(p.x, p.y, p.z);
      L.setOrientation(f.x, f.y, f.z, up.x, up.y, up.z);
    }
    const now = this.ctx.currentTime;
    const dt = Math.min(0.25, Math.max(0, now - (this.lastT || now)));
    this.lastT = now;
    this.update(dt);
  }

  private update(dt: number): void {
    // spatial filters ~15 Hz
    this.spatialTick += dt;
    if (this.spatialTick > 0.066) {
      this.spatialTick = 0;
      for (const v of this.voices) if (v.panner) v.updateSpatial();
    }
    // ambience crossfades (about 1.5 s for a full fade)
    for (const [name, a] of this.amb) {
      const step = dt / 1.5;
      a.cur += THREE.MathUtils.clamp(a.target - a.cur, -step, step);
      if (a.cur > 0.001 && a.voices.length === 0) this.startBed(name, a);
      for (const v of a.voices) (v as VoiceImpl).setVol(a.cur * a.cur * (3 - 2 * a.cur), 0.1);
      if (a.cur <= 0.001 && a.target <= 0 && a.voices.length) {
        for (const v of a.voices) v.stop(0.1);
        a.voices = [];
      }
    }
    if (this.wildlifeEnabled && this.unlocked) this.updateWildlife(dt);
  }

  // ------------------------------------------------------------------ ambience
  /** Set the target weight (0..1) of an ambience bed; it fades there smoothly. Names: see AMBIENCES (or a loop id). */
  ambience(name: string, weight: number): void {
    const w = THREE.MathUtils.clamp(weight, 0, 1);
    let a = this.amb.get(name);
    if (!a) {
      if (w <= 0) return;
      a = { target: w, cur: 0, voices: [] };
      this.amb.set(name, a);
      if (this.ctx) this.startBed(name, a);
      return;
    }
    a.target = w;
  }

  ambienceWeights(): Record<string, number> {
    const o: Record<string, number> = {};
    for (const [k, a] of this.amb) o[k] = a.cur;
    return o;
  }

  private startBed(name: string, a: { voices: Voice[] }): void {
    const spec = AMBIENCES[name] ?? { ids: [SOUNDS[name] ? name : `amb_${name}`], outdoor: true };
    for (const id of spec.ids) {
      const def = SOUNDS[id];
      if (!def) { console.warn('[audio] unknown ambience', name); continue; }
      const v = this.play(id, { loop: true, vol: 0.0001, fadeIn: 0.5 });
      if (v && spec.outdoor) {
        const vi = v as VoiceImpl;
        vi.fade.disconnect();
        vi.fade.connect(this.ambOut!);
        vi.fade.connect(vi.send);
      }
      if (v) a.voices.push(v);
    }
  }

  /** 0 = outside, 1 = inside a closed building: muffles and lowers outdoor beds. */
  setIndoors(f: number): void {
    this.indoors = THREE.MathUtils.clamp(f, 0, 1);
    if (!this.ctx) return;
    const t = this.ctx.currentTime;
    this.ambFilter!.frequency.setTargetAtTime(20000 * Math.pow(700 / 20000, this.indoors), t, 0.15);
    this.ambOut!.gain.setTargetAtTime(1 - 0.55 * this.indoors, t, 0.15);
  }

  // ------------------------------------------------------------------ world state
  setHour(h: number): void { this.hour = ((h % 24) + 24) % 24; }
  setWeather(w: Partial<Weather>): void { Object.assign(this.weather, w); }
  setHabitat(h: Record<string, number>): void { Object.assign(this.habitat, h); }
  setDread(d: number): void { this.dread = THREE.MathUtils.clamp(d, 0, 1); }
  setOcclusion(fn: ((pos: THREE.Vector3) => number) | null): void { this.occlusionFn = fn; }

  private updateWildlife(dt: number): void {
    for (const e of WILDLIFE) {
      if (!SOUNDS[e.id]) continue;
      const w = e.weight(this.hour, this.weather, this.habitat, this.dread);
      let t = this.wildTimers.get(e.id);
      if (t === undefined) { t = this.nextWild(e, Math.max(w, 0.05)) * Math.random(); }
      t -= dt * Math.max(0, w);
      if (t <= 0) {
        if (w > 0.02) this.spawnWild(e);
        t = this.nextWild(e, 1);
      }
      this.wildTimers.set(e.id, t);
    }
  }

  private nextWild(e: WildEntry, _w: number): number {
    // exponential inter-arrival (seconds at full weight), clamped so calls never machine-gun
    const mean = 60 / e.rate;
    return Math.max(mean * 0.25, -Math.log(1 - Math.random()) * mean);
  }

  private spawnWild(e: WildEntry): Voice | null {
    const a = Math.random() * Math.PI * 2;
    const d = e.dist[0] + Math.random() * (e.dist[1] - e.dist[0]);
    const hy = e.height ? e.height[0] + Math.random() * (e.height[1] - e.height[0]) : 1;
    const p = new THREE.Vector3(this.listenerPos.x + Math.cos(a) * d, this.listenerPos.y + hy, this.listenerPos.z + Math.sin(a) * d);
    return this.play(e.id, { pos: p });
  }

  /** Fire one wildlife / weather one-shot now (for testing or scripted moments). */
  triggerWildlife(id: string): Voice | null {
    const e = WILDLIFE.find((x) => x.id === id);
    return e ? this.spawnWild(e) : null;
  }

  // ------------------------------------------------------------------ reverb
  /** Crossfade the shared reverb to a zone (impulse responses generated in code). */
  setReverb(zone: ReverbZone, fade = 0.6): void {
    this.zone = zone;
    const ctx = this.ctx;
    if (!ctx) return;
    const z = ZONES[zone];
    const next = this.convs[(this.convIdx + 1) % 2];
    const cur = this.convs[this.convIdx];
    next.conv.buffer = makeIR(ctx, z.len, z.decay, z.damp, z.pre, z.er, z.seed);
    const t = ctx.currentTime;
    next.out.gain.setTargetAtTime(z.wet, t, Math.max(0.01, fade / 3));
    cur.out.gain.setTargetAtTime(0, t, Math.max(0.01, fade / 3));
    this.convIdx = (this.convIdx + 1) % 2;
  }

  // ------------------------------------------------------------------ volumes
  setVolume(cat: SoundCat | 'master', v: number): void {
    this.vols[cat] = Math.max(0, v);
    this.applyVolumes();
  }
  getVolume(cat: SoundCat | 'master'): number { return this.vols[cat] ?? 1; }
  private applyVolumes(): void {
    if (!this.ctx) return;
    const t = this.ctx.currentTime;
    this.master!.gain.setTargetAtTime(this.vols.master, t, 0.03);
    for (const c of Object.keys(this.buses) as SoundCat[]) this.buses[c]!.gain.setTargetAtTime(this.vols[c] ?? 1, t, 0.03);
  }

  get activeVoices(): number { return this.voices.size; }
}

/** Stereo impulse response: early reflections + exponentially decaying noise whose highs die faster (damping). */
export function makeIR(ctx: BaseAudioContext, len: number, decay: number, damp: number, pre: number, er: number[], seed: number): AudioBuffer {
  const sr = ctx.sampleRate;
  const n = Math.floor(len * sr);
  const buf = ctx.createBuffer(2, n, sr);
  let s = seed * 9301 + 49297;
  const rnd = () => { s = (s * 16807) % 2147483647; return (s / 2147483647) * 2 - 1; };
  for (let c = 0; c < 2; c++) {
    const d = buf.getChannelData(c);
    let lp = 0;
    const p0 = Math.floor(pre * sr);
    for (let i = p0; i < n; i++) {
      const t = (i - p0) / sr;
      // cutoff falls over the tail: bright start, dark end
      const fc = damp * Math.exp(-t / (decay * 0.8)) + 200;
      const a = Math.exp((-2 * Math.PI * fc) / sr);
      lp = (1 - a) * rnd() + a * lp;
      d[i] = lp * Math.exp((-6.91 * t) / decay) * 3;
    }
    for (const e of er) {
      const k = Math.floor((e * (1 + (c ? 0.07 : -0.05)) + pre) * sr);
      if (k < n) d[k] += (rnd() > 0 ? 1 : -1) * (0.35 + 0.4 * Math.abs(rnd())) * Math.exp(-e / (decay * 0.5));
    }
    // normalise energy so zones are comparable
    let e2 = 0;
    for (let i = 0; i < n; i++) e2 += d[i] * d[i];
    const g = 1 / Math.sqrt(e2 + 1e-9);
    for (let i = 0; i < n; i++) d[i] *= g;
  }
  return buf;
}

