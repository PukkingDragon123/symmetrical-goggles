// BUSHED audio engine: Web Audio, no dependencies beyond three (for the camera / vector types).
//
//   audio.unlock()                          on the first user gesture (also auto-armed on first pointer/key event)
//   audio.play(id, { pos?, vol?, rate?, loop? }) -> Voice | null
//   audio.setListener(camera)               every frame (also drives ambience fades, wildlife, occlusion, distance)
//   audio.ambience('forest_day', 0..1)      looping stereo beds, smooth crossfades
//   audio.setHour(h) / setWeather({ rain, wind, storm }) / setHabitat({ lake, creek }) / setDread(0..1)
//   audio.setReverb('outdoor' | 'cabin' | 'store') / setIndoors(0..1) / setOcclusion((pos) => 0..1)
//   audio.setVolume('sfx' | 'amb' | 'ui' | 'voice' | 'music' | 'master', v) / preload(ids)
//
// Sound ids and files: ./bank.ts (generated by tools/sounds/build_sounds.py).
import * as THREE from 'three';
import { SOUNDS, type SoundCat, type SoundDef } from './bank';

export type Vec3Like = THREE.Vector3 | { x: number; y: number; z: number } | [number, number, number];
export type ReverbZone = 'outdoor' | 'cabin' | 'store';

export interface PlayOpts {
  pos?: Vec3Like;        // world position (metres): plays spatially (HRTF + inverse distance). Omit for 2D.
  vol?: number;          // linear gain multiplier (on top of the bank volume)
  rate?: number;         // playback rate (pitch), before the bank's random jitter
  loop?: boolean;        // override the bank's loop flag
  delay?: number;        // seconds before it starts
  offset?: number;       // seconds into the buffer (loops: random if omitted)
  variant?: number;      // force a variation index
  reverb?: number;       // reverb send override (0..1)
  fadeIn?: number;       // seconds
}

export interface Voice {
  readonly id: string;
  readonly playing: boolean;
  setPos(p: Vec3Like): void;
  setVol(v: number, ramp?: number): void;
  setRate(r: number, ramp?: number): void;
  stop(fade?: number): void;
  onEnded?: () => void;
}

